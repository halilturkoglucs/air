import type { AirDocument } from "@air/schema";
import { snakeCase, tableName } from "./naming.js";
import type { PlannedPythonFile, ResolvedPythonTargetOptions } from "./types.js";

function metadata(air: AirDocument) {
  return Object.fromEntries(Object.entries(air.spec.entities).map(([name, entity]) => {
    const primary = Object.entries(entity.fields).find(([, field]) => field.primaryKey)?.[0] ?? (entity.fields.id ? "id" : undefined);
    return [name, { collection: tableName(name), primary, fields: entity.fields }];
  }));
}

function renderApplication(air: AirDocument): string {
  const encodedAir = JSON.stringify(JSON.stringify(air));
  const encodedEntities = JSON.stringify(JSON.stringify(metadata(air)));
  return `# Generated by AIR. Changes are overwritten in managed mode.
from __future__ import annotations

import os
from datetime import datetime, timezone
from typing import Any
from uuid import uuid4

import jwt
from fastapi import FastAPI, HTTPException, Request
from fastapi.encoders import jsonable_encoder
from fastapi.responses import JSONResponse, Response
from pymongo import ASCENDING, DESCENDING, MongoClient, ReturnDocument
from pymongo.errors import DuplicateKeyError, PyMongoError

AIR = __import__("json").loads(${encodedAir})
ENTITIES = __import__("json").loads(${encodedEntities})


def database_url() -> str:
    value = os.getenv("DATABASE_URL")
    if not value:
        raise RuntimeError("DATABASE_URL is required")
    return value


client: MongoClient[dict[str, Any]] = MongoClient(database_url())
database = client[os.getenv("MONGODB_DATABASE", "air")]
app = FastAPI(title=AIR["metadata"].get("displayName", AIR["metadata"]["name"]), version=AIR["metadata"]["version"])


@app.exception_handler(DuplicateKeyError)
def duplicate_key(_request: Request, _error: DuplicateKeyError):
    return JSONResponse(status_code=409, content={"error": {"code": "CONFLICT", "message": "A unique value already exists.", "retryable": False}})


@app.exception_handler(PyMongoError)
def database_error(_request: Request, error: PyMongoError):
    return JSONResponse(status_code=500, content={"error": {"code": "DATABASE_ERROR", "message": str(error), "retryable": True}})


def initialize_indexes() -> None:
    for entity in ENTITIES.values():
        for name, field in entity["fields"].items():
            if field.get("primaryKey") or field.get("unique"):
                database[entity["collection"]].create_index([(name, ASCENDING)], unique=True, name=f"air_{name}_unique")


initialize_indexes()


def authorize(operation: dict[str, Any], request: Request) -> dict[str, Any] | None:
    policy = operation.get("authorization")
    if not policy:
        return None
    value = request.headers.get("authorization", "")
    secret = os.getenv("AIR_AUTH_SECRET")
    if not value.startswith("Bearer ") or not secret:
        raise HTTPException(status_code=401, detail={"code": "UNAUTHENTICATED", "message": "Authentication is required."})
    try:
        principal = jwt.decode(value[7:], secret, algorithms=["HS256"])
    except jwt.PyJWTError as error:
        raise HTTPException(status_code=401, detail={"code": "UNAUTHENTICATED", "message": "Authentication failed."}) from error
    for rule in policy.get("rules", []):
        if principal.get(rule["principalField"]) not in rule["values"]:
            raise HTTPException(status_code=403, detail={"code": "FORBIDDEN", "message": "The authenticated principal cannot perform this operation."})
    return principal


def generated_value(field: dict[str, Any]) -> Any:
    generated = field.get("generated")
    if generated == "uuid":
        return str(uuid4())
    if generated in ("created-at", "updated-at"):
        return datetime.now(timezone.utc).isoformat()
    return field.get("default")


def validate_payload(entity: dict[str, Any], payload: Any, update: bool) -> dict[str, Any]:
    if not isinstance(payload, dict):
        raise HTTPException(status_code=400, detail={"code": "INVALID_INPUT", "message": "Expected a JSON object."})
    allowed = {name for name, field in entity["fields"].items() if not field.get("generated") and (not update or name != entity.get("primary"))}
    unknown = set(payload) - allowed
    if unknown:
        raise HTTPException(status_code=400, detail={"code": "INVALID_INPUT", "message": f"Unknown or immutable fields: {', '.join(sorted(unknown))}"})
    if not update:
        missing = [name for name, field in entity["fields"].items() if field.get("required") and not field.get("generated") and "default" not in field and name not in payload]
        if missing:
            raise HTTPException(status_code=400, detail={"code": "INVALID_INPUT", "message": f"Missing fields: {', '.join(missing)}"})
    for name, value in payload.items():
        field = entity["fields"][name]
        if value is None:
            if not field.get("nullable"):
                raise HTTPException(status_code=400, detail={"code": "INVALID_INPUT", "message": f"{name} cannot be null."})
            continue
        kind = field["type"]
        valid = (kind in ("string", "uuid", "date", "datetime") and isinstance(value, str)) or (kind == "integer" and isinstance(value, int) and not isinstance(value, bool)) or (kind == "number" and isinstance(value, (int, float)) and not isinstance(value, bool)) or (kind == "boolean" and isinstance(value, bool)) or kind == "json"
        if not valid:
            raise HTTPException(status_code=400, detail={"code": "INVALID_INPUT", "message": f"Invalid value for {name}."})
        choices = field.get("validation", {}).get("enum")
        if choices is not None and value not in choices:
            raise HTTPException(status_code=400, detail={"code": "INVALID_INPUT", "message": f"Invalid value for {name}."})
    return payload


def query_value(value: str, field: dict[str, Any]) -> Any:
    kind = field["type"]
    try:
        if kind == "integer":
            return int(value)
        if kind == "number":
            return float(value)
        if kind == "boolean" and value in ("true", "false"):
            return value == "true"
    except ValueError as error:
        raise HTTPException(status_code=400, detail={"code": "INVALID_INPUT", "message": "Invalid collection filter."}) from error
    return value


def public(document: dict[str, Any] | None) -> dict[str, Any] | None:
    if document is not None:
        document.pop("_id", None)
    return document


def identifier_filter(operation: dict[str, Any], request: Request, entity: dict[str, Any]) -> dict[str, Any]:
    primary = entity.get("primary")
    if not primary:
        raise HTTPException(status_code=500, detail={"code": "INVALID_MODEL", "message": "Entity has no primary field."})
    value = next(iter(request.path_params.values()), None)
    field = entity["fields"][primary]
    if field["type"] == "integer":
        try:
            value = int(value)
        except (TypeError, ValueError) as error:
            raise HTTPException(status_code=400, detail={"code": "INVALID_INPUT", "message": "Invalid identifier."}) from error
    return {primary: value}


def collection_endpoint(operation: dict[str, Any]):
    def endpoint(request: Request):
        authorize(operation, request)
        entity = ENTITIES[operation["entity"]]
        collection = operation.get("collection", {})
        query: dict[str, Any] = {}
        for item in collection.get("filters", []):
            value = request.query_params.get(item["parameter"])
            if value is not None:
                query[item["field"]] = query_value(value, entity["fields"][item["field"]])
        cursor = database[entity["collection"]].find(query, {"_id": 0})
        ordering = [(item["field"], ASCENDING if item["direction"] == "asc" else DESCENDING) for item in collection.get("orderBy", [])]
        if ordering:
            cursor = cursor.sort(ordering)
        pagination = collection.get("pagination")
        if pagination:
            try:
                limit = int(request.query_params.get("limit", pagination["defaultLimit"]))
                offset = int(request.query_params.get("offset", 0))
            except ValueError as error:
                raise HTTPException(status_code=400, detail={"code": "INVALID_INPUT", "message": "Invalid pagination."}) from error
            if limit < 1 or limit > pagination["maxLimit"] or offset < 0:
                raise HTTPException(status_code=400, detail={"code": "INVALID_INPUT", "message": "Invalid pagination."})
            cursor = cursor.skip(offset).limit(limit)
        return list(cursor)
    return endpoint


def crud_endpoint(operation: dict[str, Any]):
    async def endpoint(request: Request):
        authorize(operation, request)
        entity = ENTITIES[operation["entity"]]
        collection = database[entity["collection"]]
        action = operation["action"]
        if action == "create":
            payload = validate_payload(entity, await request.json(), False)
            row = {}
            for name, field in entity["fields"].items():
                if name in payload:
                    row[name] = payload[name]
                elif field.get("generated") or "default" in field:
                    row[name] = generated_value(field)
                elif field.get("nullable") or not field.get("required"):
                    row[name] = None
            collection.insert_one(dict(row))
            return JSONResponse(status_code=201, content=jsonable_encoder(row))
        selector = identifier_filter(operation, request, entity)
        if action == "read":
            row = public(collection.find_one(selector))
        elif action == "update":
            changes = validate_payload(entity, await request.json(), True)
            changes.pop(entity.get("primary"), None)
            for name, field in entity["fields"].items():
                if field.get("generated") == "updated-at":
                    changes[name] = datetime.now(timezone.utc).isoformat()
            if not changes:
                raise HTTPException(status_code=400, detail={"code": "INVALID_INPUT", "message": "Update payload has no mutable fields."})
            row = public(collection.find_one_and_update(selector, {"$set": changes}, return_document=ReturnDocument.AFTER))
        else:
            result = collection.delete_one(selector)
            if result.deleted_count == 0:
                raise HTTPException(status_code=404, detail={"code": "NOT_FOUND", "message": "Resource not found."})
            return Response(status_code=204)
        if row is None:
            raise HTTPException(status_code=404, detail={"code": "NOT_FOUND", "message": "Resource not found."})
        return row
    return endpoint


for operation in AIR["spec"].get("http", {}).get("operations", []):
    if "entity" not in operation:
        continue
    handler = collection_endpoint(operation) if operation["action"] == "list" else crud_endpoint(operation)
    app.add_api_route(operation["path"], handler, methods=[operation["method"]], name=operation["id"])


@app.get("/air-runtime/health")
def health():
    return {"status": "ok"}


@app.get("/air-runtime/ready")
def ready():
    try:
        database.command("ping")
        return {"status": "ready"}
    except PyMongoError as error:
        return JSONResponse(status_code=503, content={"status": "not_ready", "error": {"code": "DATABASE_UNAVAILABLE", "message": str(error), "retryable": True}})
`;
}

